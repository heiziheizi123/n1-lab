-- N1 LAB public approved original questions
create table if not exists public.questions (
 id bigint generated by default as identity primary key,
 category text not null check (category in ('vocab','grammar','reading')),
 subtype text not null default 'general',
 stem text not null,
 choices jsonb not null check (jsonb_typeof(choices)='array' and jsonb_array_length(choices)=4),
 answer_index integer not null check(answer_index between 0 and 3),
 explanation text not null default '',
 difficulty integer not null default 3 check(difficulty between 1 and 5),
 source text not null default 'original',
 status text not null default 'draft' check(status in ('draft','approved','rejected')),
 created_at timestamptz not null default now()
);
create index if not exists questions_approved_category_idx on public.questions(status,category);
alter table public.questions enable row level security;
drop policy if exists "authenticated read approved questions" on public.questions;
create policy "authenticated read approved questions" on public.questions for select to authenticated using (status='approved');
